#!/usr/bin/env node
/**
 * Generates every shopify.app*.toml from stores.json so scopes, webhooks and
 * the app proxy can't drift between registrations (they had: two configs were
 * missing the order/customer/checkout webhooks the points engine needs).
 *
 *   node scripts/generate-shopify-configs.mjs          write the files
 *   node scripts/generate-shopify-configs.mjs --check  exit 1 if any file is stale
 *
 * An app with its own "appUrl" in stores.json is still served by a separate
 * deployment. Remove that line once its credentials are in SHOPIFY_APPS on the
 * main service, then regenerate and `shopify app deploy --config <name>`.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const WEBHOOK_TOPICS = [
  "app/uninstalled",
  "orders/paid",
  "orders/cancelled",
  "refunds/create",
  "customers/create",
  "customers/update",
  "checkouts/create",
  "checkouts/update",
  "products/create",
  "products/update",
  "products/delete",
];

function fail(message) {
  console.error(`generate-shopify-configs: ${message}`);
  process.exit(1);
}

function validate(config) {
  const { appUrl, scopes, apps } = config;
  if (!/^https:\/\/[^/\s]+$/.test(appUrl ?? "")) {
    fail('"appUrl" must be an https URL with no path or trailing slash.');
  }
  if (!scopes) fail('"scopes" is required.');
  if (!Array.isArray(apps) || apps.length === 0) fail('"apps" must be a non-empty array.');

  const files = new Set();
  const clientIds = new Set();
  for (const app of apps) {
    for (const key of ["file", "name", "clientId"]) {
      if (!app[key]) fail(`every app needs "${key}" (got ${JSON.stringify(app)}).`);
    }
    if (!/^shopify\.app(\.[a-z0-9-]+)?\.toml$/.test(app.file)) {
      fail(`"${app.file}" must look like shopify.app.toml or shopify.app.<name>.toml.`);
    }
    if (app.appUrl && !/^https:\/\/[^/\s]+$/.test(app.appUrl)) {
      fail(`${app.file}: "appUrl" must be an https URL with no path or trailing slash.`);
    }
    if (files.has(app.file)) fail(`duplicate file ${app.file}.`);
    if (clientIds.has(app.clientId)) {
      fail(`client ID ${app.clientId} is used twice (${app.file}); one registration, one file.`);
    }
    files.add(app.file);
    clientIds.add(app.clientId);
  }
}

function render(app, config) {
  const url = app.appUrl ?? config.appUrl;
  const topics = WEBHOOK_TOPICS.map((topic) => `    "${topic}"`).join(",\n");

  return `# GENERATED by scripts/generate-shopify-configs.mjs from stores.json.
# Do not edit by hand - change stores.json and run \`npm run configs:generate\`.

client_id = "${app.clientId}"
name = "${app.name}"
application_url = "${url}"
embedded = true

[build]
automatically_update_urls_on_dev = true

[webhooks]
api_version = "2025-01"

  # The points engine depends on orders/* and customers/*; the abandoned-cart
  # poller depends on checkouts/*.
  [[webhooks.subscriptions]]
  topics = [
${topics}
  ]
  uri = "/webhooks"

  # Mandatory for public apps; harmless on custom ones.
  [webhooks.privacy_compliance]
  customer_data_request_url = "${url}/webhooks"
  customer_deletion_url = "${url}/webhooks"
  shop_deletion_url = "${url}/webhooks"

[access_scopes]
# read_checkouts is required by the abandoned-cart poller and the
# checkouts/create|update handlers in app/routes/webhooks.tsx.
scopes = "${config.scopes}"
use_legacy_install_flow = false

[auth]
redirect_urls = [
  "${url}/auth/callback"
]

[app_proxy]
# subpath/prefix must be identical for every app - the storefront widget JS
# has "/apps/loyalty/..." hardcoded in its fetch calls.
url = "${url}/api/proxy"
subpath = "loyalty"
prefix = "apps"

[pos]
embedded = false
`;
}

const config = JSON.parse(readFileSync(join(root, "stores.json"), "utf8"));
validate(config);

let stale = 0;
for (const app of config.apps) {
  const path = join(root, app.file);
  const next = render(app, config);
  // Compare ignoring CRLF so a Windows checkout doesn't read as "stale".
  const current = existsSync(path) ? readFileSync(path, "utf8").replace(/\r\n/g, "\n") : null;

  if (current === next) continue;
  stale += 1;
  if (check) {
    console.error(`out of date: ${app.file}`);
  } else {
    writeFileSync(path, next);
    console.log(`wrote ${app.file}`);
  }
}

if (check && stale > 0) {
  console.error("\nRun `npm run configs:generate` and commit the result.");
  process.exit(1);
}
if (!check && stale === 0) console.log("All Shopify configs already up to date.");
